def test_sync_false_returns_promptly_and_worker_runs_independently(provisioned_project):
    """sync=false returns with a non-terminal run while the worker is blocked."""
    project_id, uow_factory, _registry, root = provisioned_project
    with uow_factory.for_project(project_id) as uow:
        plan_id = uow.plans.create_plan(project_id, "Plan")
        pv_id = uow.plans.create_version(
            plan_id,
            [StepSpec(
                step_id="s1", node_type="cardre.noop", node_version="1",
                category="transform", params={}, params_hash=json_logical_hash({}),
                parent_step_ids=[], branch_label="", position=0, canonical_step_id="s1",
            )],
            is_committed=True,
        )
        uow.commit()

    harness = _BlockingHarness()
    dispatcher = ThreadRunDispatcher(harness.execute, max_workers=1)
    submit = SubmitRun(
        lambda: uow_factory.for_project(project_id),
        dispatcher,
        lambda cmd: harness.execute(RunRequest(cmd.run_id, pv_id, project_id)),
        None,
        governance_enabled=True,
        project_id=project_id,
    )

    start = time.monotonic()
    result = submit(_cmd(pv_id, sync=False))
    elapsed = time.monotonic() - start

    # The route returns promptly with a non-terminal run.
    assert elapsed < 1.0, f"sync=false blocked the request for {elapsed:.2f}s"
    assert result.status == "created"

    # The worker starts independently and finishes when released.
    harness.wait_started(result.run_id)
    harness.release[result.run_id].set()
    harness.wait_finished(result.run_id)
    assert harness.executed == [result.run_id]
    dispatcher.shutdown()


def test_sync_true_blocks_until_terminal(provisioned_project):
    """sync=true runs inline: the response is terminal only after completion."""
    project_id, uow_factory, _registry, root = provisioned_project
    with uow_factory.for_project(project_id) as uow:
        plan_id = uow.plans.create_plan(project_id, "Plan")
        pv_id = uow.plans.create_version(
            plan_id,
            [StepSpec(
                step_id="s1", node_type="cardre.noop", node_version="1",
                category="transform", params={}, params_hash=json_logical_hash({}),
                parent_step_ids=[], branch_label="", position=0, canonical_step_id="s1",
            )],
            is_committed=True,
        )
        uow.commit()

    harness = _BlockingHarness()
    dispatcher = ThreadRunDispatcher(harness.execute, max_workers=1)
    completed = {"value": False}

    def blocking_execute(cmd):
        harness.execute(RunRequest(cmd.run_id, pv_id, project_id))
        completed["value"] = True

    submit = SubmitRun(
        lambda: uow_factory.for_project(project_id),
        dispatcher,
        blocking_execute,
        None,
        governance_enabled=True,
        project_id=project_id,
    )

    result = submit(_cmd(pv_id, sync=True))
    assert completed["value"] is True, "sync=true returned before execution finished"
    assert result.status == "created"  # fake executor returns without terminalizing
    harness.wait_started(result.run_id)
    harness.release[result.run_id].set()
    harness.wait_finished(result.run_id)
    dispatcher.shutdown()


