def test_concurrent_guard_two_threads_exactly_one_run(provisioned_project):
    """Two submissions racing the guard produce exactly one run; the other
    gets the concurrent-run error."""
    project_id, uow_factory, _registry, root = provisioned_project
    with uow_factory.for_project(project_id) as uow:
        plan_id = uow.plans.create_plan(project_id, "Plan")
        pv_id = uow.plans.create_version(plan_id, [], is_committed=True)
        uow.commit()

    barrier = threading.Barrier(2)
    results: list[dict] = []
    lock = threading.Lock()

    def attempt():
        submit = SubmitRun(
            lambda: uow_factory.for_project(project_id),
            _noop_dispatcher(), lambda cmd: None, None,
            governance_enabled=True, project_id=project_id,
        )
        barrier.wait()
        try:
            res = submit(_cmd(pv_id, sync=False))
            with lock:
                results.append({"ok": True, "run_id": res.run_id})
        except CardreError as exc:
            with lock:
                results.append({"ok": False, "code": exc.code})

    t1 = threading.Thread(target=attempt)
    t2 = threading.Thread(target=attempt)
    t1.start()
    t2.start()
    t1.join(timeout=5)
    t2.join(timeout=5)

    ok = [r for r in results if r["ok"]]
    errs = [r for r in results if not r["ok"]]
    assert len(ok) == 1, f"expected exactly one success, got {results}"
    assert len(errs) == 1
    assert errs[0]["code"] == "CONCURRENT_RUN"

    with uow_factory.read_only(project_id) as uow:
        runs = uow.runs.list_for_plan_version(pv_id)
    active = [r for r in runs if r.status in ("created", "queued", "running") and not r.force]
    assert len(active) == 1, "never more than one active non-forced run"


def test_concurrent_guard_force_remains_allowed(provisioned_project):
    """force=true is allowed even when an active non-forced run exists."""
    project_id, uow_factory, _registry, root = provisioned_project
    with uow_factory.for_project(project_id) as uow:
        plan_id = uow.plans.create_plan(project_id, "Plan")
        pv_id = uow.plans.create_version(plan_id, [], is_committed=True)
        uow.commit()

    submit = SubmitRun(
        lambda: uow_factory.for_project(project_id),
        _noop_dispatcher(), lambda cmd: None, None,
        governance_enabled=True, project_id=project_id,
    )
    r1 = submit(_cmd(pv_id, sync=False))
    with pytest.raises(CardreError) as exc:
        submit(_cmd(pv_id, force=False))
    assert exc.value.code == "CONCURRENT_RUN"

    r2 = submit(_cmd(pv_id, force=True))
    assert r2.run_id != r1.run_id

    with uow_factory.read_only(project_id) as uow:
        runs = uow.runs.list_for_plan_version(pv_id)
    non_forced_active = [
        r for r in runs if r.status in ("created", "queued", "running") and not r.force
    ]
    assert len(non_forced_active) == 1


