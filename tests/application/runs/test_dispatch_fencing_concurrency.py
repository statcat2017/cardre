def test_watchdog_renews_lease_during_node_execution(provisioned_project):
    """A long-running node's heartbeat is renewed during execution, so it is
    not terminalized as stale by a subsequent submission."""
    project_id, uow_factory, _registry, root = provisioned_project
    with uow_factory.for_project(project_id) as uow:
        plan_id = uow.plans.create_plan(project_id, "Plan")
        pv_id = uow.plans.create_version(plan_id, [], is_committed=True)
        run_id = uow.runs.create(pv_id)
        uow.runs.transition(run_id, RunStatus.RUNNING,
                            expected_from=(RunStatus.CREATED, RunStatus.QUEUED))
        uow.commit()

    watchdog = HeartbeatWatchdog(
        lambda: uow_factory.for_project(project_id), run_id, interval_seconds=0.1,
    )
    watchdog.start()
    try:
        time.sleep(0.35)
    finally:
        watchdog.stop()

    with uow_factory.read_only(project_id) as uow:
        run = uow.runs.get(run_id)
    assert run is not None
    assert run.heartbeat_at is not None
    hb_ts = datetime.fromisoformat(run.heartbeat_at.replace("Z", "+00:00"))
    age = datetime.now(UTC) - hb_ts
    assert age < timedelta(seconds=1), f"heartbeat not renewed during node: age={age}"


def test_cancellation_during_final_node_ends_cancelled(provisioned_project):
    """A cancellation arriving while the final node runs must end the run as
    cancelled, never succeeded."""
    project_id, uow_factory, _registry, root = provisioned_project
    with uow_factory.for_project(project_id) as uow:
        plan_id = uow.plans.create_plan(project_id, "Plan")
        pv_id = uow.plans.create_version(
            plan_id,
            [StepSpec(
                step_id="s1", node_type="cardre.noop", node_version="1",
                category="transform", params={}, params_hash=json_logical_hash({}),
                parent_step_ids=[], branch_label="", position=0, canonical_step_id="s1",
            )],
            is_committed=True,
        )
        run_id = uow.runs.create(pv_id)  # status = created; ExecuteRun claims RUNNING
        uow.commit()

    from cardre.application.runs.execute_run import ExecuteRun, ExecuteRunCommand
    from cardre.application.runs.finalize_run import FinalizeRun
    from cardre.domain.run import RunStepStatus

    finalize = FinalizeRun(
        lambda: uow_factory.for_project(project_id),
        type("Pub", (), {"publish": lambda self, run_id, payload: None})(),
    )

    class _BlockingRunner:
        def run_step(self, *args, **kwargs):
            # Block to simulate a long final node; cancellation is set meanwhile.
            time.sleep(0.3)
            from cardre.application.execution.step_runner import StepExecutionResult
            return StepExecutionResult(
                step_id="s1", node_type="cardre.noop", status=RunStepStatus.SUCCEEDED,
                fingerprint={}, input_artifact_ids=[], output_artifact_ids=[],
                staged_artifacts=[],
            )

    class _NoopCatalogue:
        def availability(self, node_type):
            return type("Av", (), {"available": True})()

    executor = ExecuteRun(
        lambda: uow_factory.for_project(project_id),
        _NoopCatalogue(),
        _BlockingRunner(),
        finalize,
        lambda: type("Store", (), {"finalize": lambda self, s: None, "object_path": lambda self, h: ""})(),
        heartbeat_interval_seconds=0.1,
    )

    from cardre.application.runs.cancel_run import CancelRun, CancelRunCommand
    thread = threading.Thread(target=lambda: executor(ExecuteRunCommand(run_id=run_id)))
    thread.start()
    time.sleep(0.15)  # let the node block
    CancelRun(lambda: uow_factory.for_project(project_id))(CancelRunCommand(run_id=run_id))
    thread.join(timeout=5)

    with uow_factory.read_only(project_id) as uow:
        run = uow.runs.get(run_id)
    assert run is not None
    assert str(run.status) == "cancelled", f"final status: {run.status}"


def test_lost_lease_blocks_output_persistence(provisioned_project):
    """A worker whose lease was lost (run terminalized as stale) must not
    persist output after the recovery."""
    project_id, uow_factory, _registry, root = provisioned_project
    with uow_factory.for_project(project_id) as uow:
        plan_id = uow.plans.create_plan(project_id, "Plan")
        pv_id = uow.plans.create_version(
            plan_id,
            [StepSpec(
                step_id="s1", node_type="cardre.noop", node_version="1",
                category="transform", params={}, params_hash=json_logical_hash({}),
                parent_step_ids=[], branch_label="", position=0, canonical_step_id="s1",
            )],
            is_committed=True,
        )
        run_id = uow.runs.create(pv_id)  # status = created; ExecuteRun claims RUNNING
        uow.commit()

    from cardre.application.runs.execute_run import ExecuteRun, ExecuteRunCommand
    from cardre.application.runs.finalize_run import FinalizeRun
    from cardre.domain.run import RunStepStatus

    finalize = FinalizeRun(
        lambda: uow_factory.for_project(project_id),
        type("Pub", (), {"publish": lambda self, run_id, payload: None})(),
    )

    class _BlockingRunner:
        def run_step(self, *args, **kwargs):
            time.sleep(0.2)
            from cardre.application.execution.step_runner import StepExecutionResult
            return StepExecutionResult(
                step_id="s1", node_type="cardre.noop", status=RunStepStatus.SUCCEEDED,
                fingerprint={}, input_artifact_ids=[], output_artifact_ids=[],
                staged_artifacts=[],
            )

    class _NoopCatalogue:
        def availability(self, node_type):
            return type("Av", (), {"available": True})()

    persisted = {"count": 0}

    class _CountingStore:
        def finalize(self, staged):
            persisted["count"] += 1

    executor = ExecuteRun(
        lambda: uow_factory.for_project(project_id),
        _NoopCatalogue(),
        _BlockingRunner(),
        finalize,
        lambda: _CountingStore(),
        heartbeat_interval_seconds=0.1,
    )

    thread = threading.Thread(target=lambda: executor(ExecuteRunCommand(run_id=run_id)))
    thread.start()
    time.sleep(0.1)
    # Lease lost: terminalize the run as interrupted (stale recovery).
    with uow_factory.for_project(project_id) as uow:
        uow.runs.transition(run_id, RunStatus.INTERRUPTED,
                            expected_from=(RunStatus.RUNNING,))
        uow.commit()
    thread.join(timeout=5)

    # After lease loss, the worker must not have persisted any output.
    assert persisted["count"] == 0, "worker persisted output after lease loss"
    with uow_factory.read_only(project_id) as uow:
        run = uow.runs.get(run_id)
    assert str(run.status) == RunStatus.INTERRUPTED.value


